CREATE SCHEMA IF NOT EXISTS dance_palace;
REVOKE ALL ON SCHEMA dance_palace FROM PUBLIC;
CREATE TABLE IF NOT EXISTS dance_palace.users (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username text NOT NULL UNIQUE CHECK(length(username) BETWEEN 1 AND 80),
 password_hash text NOT NULL, role text NOT NULL CHECK(role IN ('admin','staff')),
 token_version integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS dance_palace.batches (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sheet_name text NOT NULL UNIQUE,
 display_name text NOT NULL UNIQUE, month_order integer[] NOT NULL DEFAULT ARRAY[4,5,6,7,8,9,10,11,12], is_event boolean NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS dance_palace.students (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, batch_id integer NOT NULL REFERENCES dance_palace.batches(id),
 sl_no integer NOT NULL, name text NOT NULL CHECK(length(trim(name))>0), register_fields jsonb NOT NULL DEFAULT '{}',
 last_activity_at timestamptz NOT NULL DEFAULT now(), UNIQUE(batch_id,name)
);
CREATE UNIQUE INDEX IF NOT EXISTS students_normalized_name ON dance_palace.students(batch_id,lower(trim(name)));
CREATE TABLE IF NOT EXISTS dance_palace.transactions (
 id text PRIMARY KEY, date date NOT NULL, type text NOT NULL CHECK(type IN ('Income','Expense')),
 category text NOT NULL, batch_display text NOT NULL, student_name text NOT NULL,
 actual_amount numeric(14,2) NOT NULL CHECK(actual_amount>=0), discounts numeric(14,2) NOT NULL DEFAULT 0 CHECK(discounts>=0),
 balance numeric(14,2) NOT NULL DEFAULT 0 CHECK(balance>=0), payment_mode text NOT NULL,
 over_paid numeric(14,2) NOT NULL DEFAULT 0 CHECK(over_paid>=0), amount numeric(14,2) NOT NULL,
 status text NOT NULL CHECK(status IN ('Completed','Pending','Cancelled')), recorded_by text NOT NULL,
 description text NOT NULL DEFAULT '', channel text NOT NULL CHECK(channel IN ('Cash','Digital')),
 net_effect numeric(14,2) NOT NULL, drive_receipt text NOT NULL DEFAULT '', legacy_months jsonb NOT NULL DEFAULT '[]',
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS dance_palace.transaction_months (
 transaction_id text NOT NULL REFERENCES dance_palace.transactions(id) ON DELETE CASCADE,
 position integer NOT NULL CHECK(position BETWEEN 0 AND 5), year integer NOT NULL CHECK(year BETWEEN 1900 AND 9999),
 month integer NOT NULL CHECK(month BETWEEN 1 AND 12), PRIMARY KEY(transaction_id,position), UNIQUE(transaction_id,year,month)
);
CREATE TABLE IF NOT EXISTS dance_palace.fee_cells (
 student_id integer NOT NULL REFERENCES dance_palace.students(id) ON DELETE CASCADE, year integer NOT NULL CHECK(year BETWEEN 1900 AND 9999),
 month integer NOT NULL CHECK(month BETWEEN 1 AND 12), status text NOT NULL CHECK(status IN ('PAID','DUE')),
 amount numeric(14,2) NOT NULL DEFAULT 0, plan text NOT NULL DEFAULT '', cg text CHECK(cg IN ('C','G')),
 PRIMARY KEY(student_id,year,month)
);
CREATE TABLE IF NOT EXISTS dance_palace.setup (key text PRIMARY KEY, values jsonb NOT NULL);
CREATE TABLE IF NOT EXISTS dance_palace.manager_tables (name text PRIMARY KEY, columns jsonb NOT NULL);
CREATE TABLE IF NOT EXISTS dance_palace.manager_rows (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, table_name text NOT NULL REFERENCES dance_palace.manager_tables(name),
 data jsonb NOT NULL, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS dance_palace.templates (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,title text NOT NULL UNIQUE,text text NOT NULL);
CREATE TABLE IF NOT EXISTS dance_palace.attendance_years (year integer PRIMARY KEY CHECK(year BETWEEN 1900 AND 9999));
CREATE TABLE IF NOT EXISTS dance_palace.attendance_sheets (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, year integer NOT NULL REFERENCES dance_palace.attendance_years(year),
 month integer NOT NULL CHECK(month BETWEEN 1 AND 12), sheet_name text NOT NULL CHECK(sheet_name<>'DATA'),
 batch_id integer REFERENCES dance_palace.batches(id), grid jsonb NOT NULL DEFAULT '[]', UNIQUE(year,month,sheet_name)
);
CREATE TABLE IF NOT EXISTS dance_palace.worklog_people (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, role text NOT NULL CHECK(role IN ('manager','faculty')), UNIQUE(name,role)
);
CREATE TABLE IF NOT EXISTS dance_palace.worklog_entries (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, person_id integer NOT NULL REFERENCES dance_palace.worklog_people(id) ON DELETE CASCADE,
 date date NOT NULL, status text NOT NULL CHECK(status IN ('Present','Leave')), login time, logout time, batch text NOT NULL DEFAULT '',
 CHECK(logout IS NULL OR (login IS NOT NULL AND logout>=login)), CHECK(status<>'Leave' OR (login IS NULL AND logout IS NULL))
);
CREATE TABLE IF NOT EXISTS dance_palace.progress_reviews (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id integer NOT NULL REFERENCES dance_palace.students(id) ON DELETE CASCADE,
 month text NOT NULL CHECK(month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'), attendance numeric(5,2) NOT NULL CHECK(attendance BETWEEN 0 AND 100),
 ratings jsonb NOT NULL, overall numeric(5,3) NOT NULL, grade text NOT NULL, status text NOT NULL,
 strengths text NOT NULL DEFAULT '', needs_improvement text NOT NULL DEFAULT '', remarks text NOT NULL DEFAULT '',
 UNIQUE(student_id,month)
);
CREATE TABLE IF NOT EXISTS dance_palace.import_sources (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, filename text NOT NULL, imported_at timestamptz NOT NULL DEFAULT now(), sheets jsonb NOT NULL);
CREATE TABLE IF NOT EXISTS dance_palace.health_checks (id integer PRIMARY KEY CHECK(id=1), checked_at timestamptz NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS transactions_student_batch ON dance_palace.transactions(lower(student_name),batch_display);
CREATE INDEX IF NOT EXISTS transactions_date ON dance_palace.transactions(date);
CREATE INDEX IF NOT EXISTS worklog_person_date ON dance_palace.worklog_entries(person_id,date);
